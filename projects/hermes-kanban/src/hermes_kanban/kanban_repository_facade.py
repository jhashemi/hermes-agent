def claim_task(
    conn: sqlite3.Connection,
    task_id: str,
    *,
    lock: Optional[str] = None,
    ttl_seconds: int = 900,
    profile: Optional[str] = None,
    step_key: Optional[str] = None,
    max_runtime_seconds: Optional[int] = None,
) -> Optional[int]:
    run_id = kanban_db.claim_task(
        conn,
        task_id,
        lock=lock,
        ttl_seconds=ttl_seconds,
        profile=profile,
        step_key=step_key,
        max_runtime_seconds=max_runtime_seconds,
    )
    with _mirror_context(conn) as duck:
        if duck is not None and run_id is not None:
            _safe_mirror(
                dka.claim_task,
                duck,
                task_id,
                lock=lock,
                ttl_seconds=ttl_seconds,
                profile=profile,
                step_key=step_key,
                max_runtime_seconds=max_runtime_seconds,
                run_id=run_id,  # id passthrough
            )
    return run_id


